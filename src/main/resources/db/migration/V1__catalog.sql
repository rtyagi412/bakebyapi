CREATE TABLE category (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(100) NOT NULL,
    slug        VARCHAR(120) NOT NULL,
    description TEXT,
    active      BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT uk_category_name UNIQUE (name),
    CONSTRAINT uk_category_slug UNIQUE (slug)
);

CREATE TABLE product (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_id     BIGINT       NOT NULL,
    name            VARCHAR(150) NOT NULL,
    slug            VARCHAR(170) NOT NULL,
    description     TEXT,
    ingredients     TEXT,
    dietary_type    VARCHAR(20)  NOT NULL,
    shelf_life_days INTEGER,
    lead_time_hours INTEGER,
    serves          INTEGER,
    active          BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at      TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at      TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT uk_product_slug UNIQUE (slug),
    CONSTRAINT fk_product_category FOREIGN KEY (category_id) REFERENCES category (id),
    CONSTRAINT ck_product_shelf_life CHECK (shelf_life_days IS NULL OR shelf_life_days >= 0),
    CONSTRAINT ck_product_lead_time CHECK (lead_time_hours IS NULL OR lead_time_hours >= 0),
    CONSTRAINT ck_product_serves CHECK (serves IS NULL OR serves >= 1)
);
CREATE INDEX idx_product_category_id ON product (category_id);

CREATE TABLE product_allergen (
    product_id BIGINT      NOT NULL,
    allergen   VARCHAR(20) NOT NULL,
    PRIMARY KEY (product_id, allergen),
    CONSTRAINT fk_product_allergen_product FOREIGN KEY (product_id) REFERENCES product (id)
);

CREATE TABLE product_image (
    product_id BIGINT       NOT NULL,
    position   INTEGER      NOT NULL,
    url        VARCHAR(500) NOT NULL,
    PRIMARY KEY (product_id, position),
    CONSTRAINT fk_product_image_product FOREIGN KEY (product_id) REFERENCES product (id)
);

CREATE TABLE variant (
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id             BIGINT       NOT NULL,
    sku                    VARCHAR(64)  NOT NULL,
    label                  VARCHAR(100) NOT NULL,
    price_minor            BIGINT       NOT NULL,
    compare_at_price_minor BIGINT,
    in_stock               BOOLEAN      NOT NULL DEFAULT TRUE,
    active                 BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at             TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at             TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT uk_variant_sku UNIQUE (sku),
    CONSTRAINT fk_variant_product FOREIGN KEY (product_id) REFERENCES product (id),
    CONSTRAINT ck_variant_price CHECK (price_minor >= 0),
    CONSTRAINT ck_variant_compare_at CHECK (compare_at_price_minor IS NULL OR compare_at_price_minor > price_minor)
);
CREATE INDEX idx_variant_product_id ON variant (product_id);
